    private void jButton4ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton4ActionPerformed
        // TODO add your handling code here:
        List<Pessoa> lstPessoa = telaPrincipal.getListaPessoa();
        posicao++;
        if(posicao < lstPessoa.size()){
            Pessoa pessoa = lstPessoa.get(posicao);
            //posicao++;
            txtNome.setText(pessoa.getNome());
            txtEndereco.setText(pessoa.getEndereco());
            txtEmail.setText(pessoa.getEmail());
        }else{
            JOptionPane.showMessageDialog(null, "Não há mais Cadastros");
            posicao = -1;
            limparTela();
        }
    }//GEN-LAST:event_jButton4ActionPerformed

    private void jButton3ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton3ActionPerformed
        // TODO add your handling code here:
        List<Pessoa> lstPessoa = telaPrincipal.getListaPessoa();
        posicao--;
        if(posicao > -1){
            Pessoa pessoa = lstPessoa.get(posicao);
 
            txtNome.setText(pessoa.getNome());
            txtEndereco.setText(pessoa.getEndereco());
            txtEmail.setText(pessoa.getEmail());
        }else{
            JOptionPane.showMessageDialog(null, "Não há mais Cadastros");
            posicao = -1;
            limparTela();
        }
    }//GEN-LAST:event_jButton3ActionPerformed

    private void jButton5ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton5ActionPerformed
        // TODO add your handling code here:
        List<Pessoa> lstPessoa = telaPrincipal.getListaPessoa();
        if (posicao < 0 || posicao >= lstPessoa.size()){
            JOptionPane.showMessageDialog(null, "Não há nenhum cadastro");
            return;
        }
        int resposta = JOptionPane.showConfirmDialog(null, 
                "Deseja realmente excluir este cadastro?", 
                "Confirmação", JOptionPane.YES_NO_OPTION);
        if (resposta == JOptionPane.YES_OPTION){
            lstPessoa.remove(posicao);
            if (lstPessoa.isEmpty()){
                posicao = -1;
                limparTela();
            }else{
                if (posicao >= lstPessoa.size()){
                    posicao = lstPessoa.size() -1;
                }
                mostrarPessoa(posicao);
            }
            JOptionPane.showMessageDialog(null, "Cadastro Excluído com Sucesso");
        }
    }//GEN-LAST:event_jButton5ActionPerformed


