    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        // TODO add your handling code here:
        if(camposPreenchidos()){
            Pessoa pessoa = new Pessoa();
            pessoa.setNome(txtNome.getText());
            pessoa.setEndereco(txtEndereco.getText());
            pessoa.setEmail(txtEmail.getText());
            String mensagem = "";
            //se a variável posição == -1 gravar novo registro
            //senão (!=) atualizar registro
            
            //adicionar essa pessoa no array listaPessoas na tela principal
            if(posicao == -1){
                telaPrincipal.addPessoaLista(pessoa);
                mensagem = "Pessoa Cadastrada com Sucesso!";
            }else{
                telaPrincipal.atualizarPessoaLista(pessoa, posicao);
                mensagem = "Pessoa Atualizada com Sucesso!";
            }
            limparTela();
            posicao = -1;
            JOptionPane.showMessageDialog(null, mensagem);
        }else{
            JOptionPane.showMessageDialog(null, "Preencha todos os campos!");
        }
    }//GEN-LAST:event_jButton1ActionPerformed

