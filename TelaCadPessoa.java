    private void limparTela(){
        txtNome.setText("");
        txtEndereco.setText("");
        txtEmail.setText("");
        txtNome.requestFocusInWindow();
    }
    
    //método para exibir todas as pessoas da lista
    private void listarPessoas(){
        List<Pessoa> lstPessoa = telaPrincipal.getListaPessoa();
        String texto = "";
        for(Pessoa p: lstPessoa){
            //+= --> texto = texto + concatenar 
            texto += p.toString() + "\n ----------------------------- \n";
        }
        JOptionPane.showMessageDialog(null, texto);
    }

    private boolean camposPreenchidos() {
        boolean resposta = true;
        //vamos validar os campos
        if(txtNome.getText().length() == 0){
            resposta = false;
        }
        if(txtEndereco.getText().length() == 0 && resposta){
            resposta = false;
        }
        if(txtEmail.getText().length() == 0 && resposta){
            resposta = false;
        }
        return resposta;
    }
    
    private void mostrarPessoa(int pos){
        Pessoa pessoa = telaPrincipal.getListaPessoa().get(pos);
        txtNome.setText(pessoa.getNome());
        txtEndereco.setText(pessoa.getEndereco());
        txtEmail.setText(pessoa.getEmail());
    }
